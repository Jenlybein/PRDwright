@dataclass(frozen=True)
class ConversationProfile:
    """一套完整的对话提示词配置：系统人设 + 首轮开场白。

    两者打包在一起，是为了让「必须同口径」这件事由类型结构来保证，而不是靠人的记忆。

    Attributes:
        key: 档案标识。会话记录里存的就是它，而不是解析后的文本——这样改提示词对
            进行中的会话也能即时生效，库里也不会留下「冻结的旧人设」。
        label: 展示名，用于日志与排查。
        system_prompt: 系统人设。
        opening: 首轮开场白模板，用 `str.format()` 按 `opening_fields` 声明的占位符填充。
        opening_fields: 开场白里要用到的占位符名。`requirements` 是唯一的保留名
            （「问卷答案整理成的需求文本」，由本地格式化产出）；其余名字一律按同名键
            从提交上来的表单数据里取。**声明与模板必须一一对应**——多写一个会在
            渲染时 `KeyError`，少写一个则拿不到值，两个方向都有测试守着。
    """

    key: str
    label: str
    system_prompt: str
    opening: str
    opening_fields: tuple[str, ...] = ("requirements",)


# 文档澄清档案的标识。服务层要按它分流（如状态文案），抽成常量避免多处硬编码后各自漂移。
DOC_CLARIFICATION_PROFILE_KEY = "doc-clarification"

